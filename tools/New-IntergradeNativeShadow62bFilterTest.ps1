    'mad r12.xy, r24.xyxx, l(-2.000000, 2.000000, 0.000000, 0.000000), r12.xyxx'
)) {
    if ($verified -notmatch [regex]::Escape($required)) { throw "Verified shader is missing: $required" }
}
if ([regex]::Matches($verified,'gather4_aoffimmi_indexable').Count -ne [regex]::Matches($source,'gather4_aoffimmi_indexable').Count) {
    throw 'Native gather instruction count changed unexpectedly.'
}

